@pytest.mark.parametrize("name,expected_key,_kind", GOLDEN_FILES)
def test_group_key_matches_legacy_set_id(name, expected_key, _kind):
    assert I.group_key("/d/" + name) == expected_key


@pytest.mark.parametrize("name,_key,expected_kind", GOLDEN_FILES)
def test_refl1d_import_state_kind_unchanged(name, _key, expected_kind):
    assert _detect_state_kind(["/d/" + name]) == expected_kind


