def test_unknown_file_falls_back_to_generic():
    inst = I.resolve_by_name("/d/mystery.xyz")
    assert inst.name == "generic"
    assert inst.file_role("/d/mystery.xyz") == UNKNOWN
    assert inst.group_key("/d/mystery.xyz") is None
