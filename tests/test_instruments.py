def test_ref_l_claims_its_filenames():
    assert I.resolve_by_name("/d/REFL_1_2_3_partial.txt").name == "REF_L"
    assert I.resolve_by_name("/d/REFL_1_combined_data_auto.txt").name == "REF_L"


def test_unknown_file_falls_back_to_generic():
    inst = I.resolve_by_name("/d/mystery.xyz")
    assert inst.name == "generic"
    assert inst.file_role("/d/mystery.xyz") == UNKNOWN
    assert inst.group_key("/d/mystery.xyz") is None
    assert inst.header_metadata("/d/mystery.xyz") == I.DEFAULT_HEADER_METADATA


def test_resolve_by_name_never_reads_the_file(tmp_path):
    """A REF_L header must not make resolve_by_name claim a foreign name."""
    p = tmp_path / "foreign.xyz"
    p.write_text("# TwoTheta(deg)\n# 1.0\n0.01 1.0 0.1\n")
    assert I.resolve_by_name(str(p)).name == "generic"


def test_resolve_falls_back_to_a_header_sniff(tmp_path):
    """The theta heuristic used to run on every file regardless of name; a
    header sniff is what preserves that for an oddly-named REF_L file."""
    p = tmp_path / "oddly-named.dat"
    p.write_text("# Some preamble\n# TwoTheta(deg) other\n# 0.6 1\n0.01 1.0 0.1\n")
    assert I.resolve(str(p)).name == "REF_L"
    assert I.header_metadata(str(p))["theta"] == pytest.approx(0.3)


def test_resolve_on_a_missing_file_is_generic_not_an_error():
    assert I.resolve("/nonexistent/nope.dat").name == "generic"


