class _FakeInstrument:
    """A third-party instrument, registered the way a plugin would."""

    name = "FAKE"

    def matches(self, file_path, header=""):
        return os.path.basename(file_path).startswith("fake_")

    def file_role(self, file_path):
        return PARTIAL

    def group_key(self, file_path):
        return os.path.basename(file_path).split("_")[1]

    def header_metadata(self, file_path):
        return {
            "dq_is_fwhm": False,
            "num_segments": 3,
            "theta": 1.25,
            "instrument": self.name,
        }

    def role_supports_nuisance(self, role):
        return True


@pytest.fixture
def fake_registered():
    I.register(_FakeInstrument(), first=True)
    yield
    from aure.instruments import registry

    registry._REGISTRY = [i for i in registry._REGISTRY if i.name != "FAKE"]


def test_a_registered_instrument_claims_its_files(fake_registered):
    assert I.resolve_by_name("/d/fake_77_a.dat").name == "FAKE"
    assert I.file_role("/d/fake_77_a.dat") == PARTIAL
    assert I.group_key("/d/fake_77_a.dat") == "77"
    assert I.header_metadata("/d/fake_77_a.dat")["theta"] == 1.25


def test_registering_does_not_disturb_ref_l(fake_registered):
    assert I.resolve_by_name("/d/REFL_1_2_3_partial.txt").name == "REF_L"


def test_a_custom_instrument_drives_the_state_classifier(fake_registered):
    ds = [{"file": "/d/fake_77_a.dat"}, {"file": "/d/fake_77_b.dat"}]
    assert _detect_kind("s", ds) == "partials"


def test_a_custom_instrument_can_reject_mixed_groups(fake_registered):
    ds = [{"file": "/d/fake_77_a.dat"}, {"file": "/d/fake_88_b.dat"}]
    with pytest.raises(ConfigError, match="set_id"):
        _detect_kind("s", ds)


def test_re_registering_a_name_replaces_it():
    from aure.instruments import registry

    before = [i.name for i in I.registered()]
    I.register(_FakeInstrument())
    I.register(_FakeInstrument())
    names = [i.name for i in I.registered()]
    assert names.count("FAKE") == 1
    registry._REGISTRY = [i for i in registry._REGISTRY if i.name != "FAKE"]
    assert [i.name for i in I.registered()] == before


