"""Instrument/format seam.

The first half is a **golden parity table**: the exact classifications the
hard-coded REF_L regexes produced before they were consolidated into
``aure.instruments``. It was generated by running the old
``config._detect_kind``, ``intake._extract_set_id``,
``refl1d_import._extract_set_id`` and ``refl1d_import._detect_state_kind``,
and it exists so that moving that logic cannot silently change what REF_L
files mean. Do not "fix" a row here without deciding that the behaviour
change is intended.
"""

import os

import pytest

from aure import instruments as I
from aure.config import ConfigError, _detect_kind
from aure.instruments import COMBINED, PARTIAL, UNKNOWN
from aure.instruments.registry import _ENV_OVERRIDE
from aure.refl1d_import import _detect_state_kind

