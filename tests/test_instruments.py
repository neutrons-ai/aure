@pytest.mark.parametrize("names,expected", GOLDEN_STATES)
def test_detect_kind_unchanged(names, expected):
    ds = [{"file": "/d/" + n} for n in names]
    assert _detect_kind("s", ds) == expected


def test_detect_kind_still_rejects_mixed_roles():
    ds = [
        {"file": "/d/REFL_226642_combined_data_auto.txt"},
        {"file": "/d/REFL_226642_1_2001_partial.txt"},
    ]
    with pytest.raises(ConfigError, match="cannot mix combined and partial"):
        _detect_kind("s", ds)


def test_detect_kind_still_rejects_mixed_set_ids():
    ds = [
        {"file": "/d/REFL_226642_1_2001_partial.txt"},
        {"file": "/d/REFL_226660_1_2001_partial.txt"},
    ]
    with pytest.raises(ConfigError, match="set_id"):
        _detect_kind("s", ds)


def test_partials_without_a_set_id_are_still_tolerated():
    """``x_1_2_partial.txt`` has a role but no group key; that combination
    passed the consistency check before and must keep passing."""
    ds = [{"file": "/d/x_1_2_partial.txt"}, {"file": "/d/y_3_4_partial.txt"}]
    assert _detect_kind("s", ds) == "partials"


